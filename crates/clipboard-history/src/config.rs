//! Configuration (serde, camelCase, every field optional).

use serde::{Deserialize, Serialize};

/// Where the picker window opens.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase")]
pub enum PickerPosition {
    /// Next to the mouse pointer (kept on the pointer's screen).
    #[default]
    Mouse,
    /// Centred on the main screen.
    Center,
}

/// `"clipboardHistory"` settings.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct Config {
    /// Record clipboard history (off by default, like Windows' Win+V).
    pub enabled: bool,
    /// Opens the picker. Default Cmd+Shift+V (macOS) / Win+Shift+V
    /// (Windows, where Win+V is the OS' own history). Empty disables it.
    pub hotkey: String,
    /// Maximum number of unpinned items kept (default 200).
    pub max_items: usize,
    /// Unpinned items older than this many days are removed; 0 keeps them
    /// until `maxItems` pushes them out. Default 30.
    pub max_age_days: u32,
    /// Keep history across restarts in `<config dir>/PowerMac/clipboard/`.
    /// When false, history lives in memory only and is gone on quit.
    pub persist: bool,
    /// Temporarily stop recording (the hotkey and picker keep working).
    pub paused: bool,
    /// Record images (stored as PNG, with a thumbnail).
    pub capture_images: bool,
    /// Record copied files (their paths).
    pub capture_files: bool,
    /// Keep the rich text / HTML of copied text (a plain-text fallback is
    /// always kept).
    pub capture_rich_text: bool,
    /// Skip anything bigger than this (MB). Default 20.
    pub max_item_mb: u32,
    /// Don't record copies made while one of these apps is in front (bundle
    /// id, app name or exe name, case-insensitive).
    pub excluded_apps: Vec<String>,
    /// Honour "don't record this" markers (`org.nspasteboard.ConcealedType`
    /// / `TransientType` / `AutoGeneratedType` on macOS,
    /// `ExcludeClipboardContentFromMonitorProcessing` and
    /// `CanIncludeInClipboardHistory = 0` on Windows). Default on.
    pub skip_concealed: bool,
    /// Choosing an item pastes it into the app that was in front. When off it
    /// is only put on the clipboard.
    pub paste_on_select: bool,
    /// Where the picker opens.
    pub picker_position: PickerPosition,
}

impl Default for Config {
    fn default() -> Self {
        Self {
            enabled: false,
            hotkey: default_hotkey().into(),
            max_items: 200,
            max_age_days: 30,
            persist: true,
            paused: false,
            capture_images: true,
            capture_files: true,
            capture_rich_text: true,
            max_item_mb: 20,
            excluded_apps: default_excluded_apps(),
            skip_concealed: true,
            paste_on_select: true,
            picker_position: PickerPosition::Mouse,
        }
    }
}

/// `Cmd+Shift+V` on macOS, `Win+Shift+V` elsewhere.
///
/// Doesn't collide with PowerMac's other hotkeys (paste as plain text is
/// Cmd+Option+Shift+V, highlighter Cmd+Shift+H, crosshairs Cmd+Option+P,
/// FancyZones Ctrl+Option+… / Ctrl+Option+Cmd+…); hotkeys match their
/// modifiers exactly. It does take over "paste and match style" in the few
/// apps that use Cmd+Shift+V for it (Chrome, Slack, ...).
pub fn default_hotkey() -> &'static str {
    if cfg!(target_os = "macos") {
        "Cmd+Shift+V"
    } else {
        "Win+Shift+V"
    }
}

/// Password managers and keychains.
pub fn default_excluded_apps() -> Vec<String> {
    [
        "1Password",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "Bitwarden",
        "com.bitwarden.desktop",
        "KeePassXC",
        "org.keepassxc.keepassxc",
        "KeePass",
        "Keychain Access",
        "com.apple.keychainaccess",
        "Passwords",
        "com.apple.Passwords",
    ]
    .into_iter()
    .map(String::from)
    .collect()
}

impl Config {
    pub fn from_json(s: &str) -> anyhow::Result<Config> {
        Ok(serde_json::from_str(s)?)
    }

    pub fn to_json(&self) -> String {
        serde_json::to_string_pretty(self).expect("config serializes")
    }

    /// The parsed hotkey (`None` when empty or invalid).
    pub fn hotkey(&self) -> Option<keyboard_manager::Shortcut> {
        let h = self.hotkey.trim();
        if h.is_empty() {
            return None;
        }
        h.parse().ok()
    }

    /// Problems worth showing in the settings window.
    pub fn validate(&self) -> Vec<String> {
        let mut out = Vec::new();
        if !self.hotkey.trim().is_empty() && self.hotkey().is_none() {
            out.push(format!("hotkey '{}' is not a valid shortcut", self.hotkey));
        }
        if self.max_items == 0 {
            out.push("maxItems is 0: only pinned items are kept".into());
        }
        out
    }

    pub(crate) fn max_item_bytes(&self) -> u64 {
        (self.max_item_mb.max(1) as u64) << 20
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn defaults_and_round_trip() {
        let c = Config::default();
        assert!(!c.enabled && c.persist && !c.paused);
        assert_eq!(c.max_items, 200);
        assert_eq!(Config::from_json("{}").unwrap(), c);
        assert_eq!(Config::from_json(&c.to_json()).unwrap(), c);
        let j = c.to_json();
        assert!(j.contains("\"maxItems\": 200") && j.contains("\"pickerPosition\": \"mouse\""));
        let h = c.hotkey().unwrap();
        assert_eq!(h.key, pm_vk_v());
        assert!(c.validate().is_empty());
    }

    fn pm_vk_v() -> u32 {
        0x56
    }

    #[test]
    fn hotkey_does_not_collide_with_other_powermac_hotkeys() {
        let ours = Config::default().hotkey().unwrap();
        let others = if cfg!(target_os = "macos") {
            vec![
                "Cmd+Option+Shift+V",
                "Cmd+Shift+H",
                "Cmd+Option+P",
                "Ctrl+Option+Left",
                "Ctrl+Option+X",
                "Ctrl+Option+Cmd+0",
                "Ctrl+Option+Cmd+Left",
            ]
        } else {
            vec!["Win+Ctrl+Alt+V", "Win+Shift+H", "Win+Alt+P", "Win+V"]
        };
        for o in others {
            let s: keyboard_manager::Shortcut = o.parse().unwrap();
            assert_ne!(s, ours, "{o}");
        }
    }

    #[test]
    fn partial_json_and_bad_hotkey() {
        let c = Config::from_json(r#"{"enabled": true, "hotkey": "Ctrl+Nope", "persist": false}"#)
            .unwrap();
        assert!(c.enabled && !c.persist && c.max_items == 200);
        assert!(c.hotkey().is_none());
        assert_eq!(c.validate().len(), 1);
        let c = Config::from_json(r#"{"hotkey": ""}"#).unwrap();
        assert!(c.hotkey().is_none() && c.validate().is_empty());
    }
}

/// `<config dir>/PowerMac/clipboard` (`~/Library/Application Support/
/// PowerMac/clipboard`, `%APPDATA%\PowerMac\clipboard`).
pub fn default_data_dir() -> Option<PathBuf> {
    #[cfg(target_os = "macos")]
    let base = std::env::var_os("HOME")
        .map(|h| PathBuf::from(h).join("Library").join("Application Support"));
    #[cfg(windows)]
    let base = std::env::var_os("APPDATA").map(PathBuf::from);
    #[cfg(not(any(target_os = "macos", windows)))]
    let base = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".config")));
    Some(base?.join("PowerMac").join("clipboard"))
}

/// The data dir next to a PowerMac `config.json` (`<dir>/clipboard`).
pub fn data_dir_for_config(config_path: &Path) -> PathBuf {
    config_path
        .parent()
        .unwrap_or(Path::new("."))
        .join("clipboard")
}

type Callback = Arc<dyn Fn() + Send + Sync>;

struct Inner {
    dir: PathBuf,
    store: Mutex<Store>,
    config: Mutex<Config>,
    /// Change count of our own last clipboard write (not recorded again).
    own_write: Mutex<Option<i64>>,
    on_open: Mutex<Option<Callback>>,
    stop: AtomicBool,
    hotkey_ok: AtomicBool,
}

impl Inner {
    fn cfg(&self) -> Config {
        self.config.lock().map(|c| c.clone()).unwrap_or_default()
    }

    fn store(&self) -> std::sync::MutexGuard<'_, Store> {
        self.store.lock().unwrap_or_else(|e| e.into_inner())
    }

    fn open_picker(&self) {
        let cb = self.on_open.lock().ok().and_then(|g| g.clone());
        match cb {
            Some(cb) => cb(),
            None => log::info!("clipboard history: hotkey pressed but no picker callback set"),
        }
    }

    /// A clipboard change happened (count `cc`).
    fn on_change(&self, cc: i64) {
        if self
            .own_write
            .lock()
            .map(|g| *g == Some(cc))
            .unwrap_or(false)
        {
            return;
        }
        let cfg = self.cfg();
        if !cfg.enabled {
            return;
        }
        let (types, source) = platform::read_meta();
        if let Some(skip) = content::skip_reason(&types, source.as_ref(), &cfg) {
            log::debug!("clipboard history: not recording ({skip:?})");
            return;
        }
        let mut cap = content::Capture {
            content: platform::read_content(&types),
            types,
            source,
        };
        if let Err(skip) = content::filter(&mut cap, &cfg) {
            log::debug!("clipboard history: not recording ({skip:?})");
            return;
        }
        match self.store().add(cap, &cfg, store::now_ms()) {
            Ok(a) => log::debug!("clipboard history: {a:?}"),
            Err(e) => log::warn!("clipboard history: saving: {e:#}"),
        }
    }

    /// Put an item on the clipboard and move it to the top.
    fn put_on_clipboard(&self, id: u64, plain: bool) -> Result<()> {
        let c = self
            .store()
            .content(id)
            .ok_or_else(|| anyhow!("no clipboard item {id}"))?;
        let cc = platform::write(&c, plain)?;
        if let Ok(mut g) = self.own_write.lock() {
            *g = Some(cc);
        }
        let mut s = self.store();
        s.touch(id, store::now_ms());
        s.save()?;
        Ok(())
    }

    fn handle(&self, req: ipc::Request) -> ipc::Response {
        use ipc::{Request as Q, Response as R};
        let cfg = self.cfg();
        let mut r = match req {
            Q::Status => R::ok(),
            Q::List { query, limit } => {
                let s = self.store();
                let mut r = R::ok();
                r.items = Some(
                    s.search(&query)
                        .into_iter()
                        .take(limit.max(1))
                        .map(|i| i.summary())
                        .collect(),
                );
                r.total = s.len();
                r
            }
            Q::Thumb { id } => match self.store().thumbnail(id) {
                Some(png) => R {
                    png: Some(ipc::b64_encode(&png)),
                    ..R::ok()
                },
                None => R::err("no thumbnail"),
            },
            Q::Pin { id, pinned } => {
                let mut s = self.store();
                if s.set_pinned(id, pinned) {
                    s.save().map_or_else(R::err, |_| R::ok())
                } else {
                    R::err("no such item")
                }
            }
            Q::Delete { id } => {
                let mut s = self.store();
                if s.delete(id) {
                    s.save().map_or_else(R::err, |_| R::ok())
                } else {
                    R::err("no such item")
                }
            }
            Q::Clear { keep_pinned } => {
                let mut s = self.store();
                s.clear(keep_pinned);
                s.save().map_or_else(R::err, |_| R::ok())
            }
            Q::Paste {
                id,
                plain,
                paste,
                pid,
            } => match self.put_on_clipboard(id, plain) {
                Ok(()) => {
                    if paste {
                        std::thread::spawn(move || paste_when_frontmost(pid));
                    }
                    R::ok()
                }
                Err(e) => R::err(format!("{e:#}")),
            },
            Q::Pause { paused } => {
                if let Ok(mut c) = self.config.lock() {
                    c.paused = paused;
                }
                R::ok()
            }
        };
        let cfg2 = self.cfg();
        r.paused = cfg2.paused;
        r.persist = cfg.persist;
        if r.total == 0 {
            r.total = self.store().len();
        }
        r
    }
}

/// Wait (up to 1.5 s) for process `pid` to be in front again, then paste.
fn paste_when_frontmost(pid: i32) {
    let t0 = Instant::now();
    while pid > 0 && !platform::is_frontmost(pid) && t0.elapsed() < Duration::from_millis(1500) {
        std::thread::sleep(Duration::from_millis(20));
    }
    // Let the app's window become key before the keystroke arrives.
    std::thread::sleep(Duration::from_millis(80));
    if let Err(e) = keyboard_manager::send_paste() {
        log::warn!("clipboard history: paste: {e:#}");
    }
}

/// Entry point.
pub struct ClipboardHistory;

impl ClipboardHistory {
    /// Load the history from `data_dir` (or start an in-memory one), start
    /// watching the clipboard, register the hotkey and serve the picker.
    /// A hotkey that can't be registered (macOS without Accessibility) is
    /// logged and [`Handle::hotkey_active`] reports false; the rest works.
    pub fn start(config: Config, data_dir: PathBuf) -> Result<Handle> {
        for w in config.validate() {
            log::warn!("clipboard history: {w}");
        }
        std::fs::create_dir_all(&data_dir)?;
        let mut st = Store::for_config(&data_dir, &config)?;
        if !config.persist {
            // A previous persistent history is removed when switching to
            // memory-only.
            let _ = Store::open(&data_dir).and_then(|mut s| s.set_dir(None));
        }
        if st.prune(&config, store::now_ms()) > 0 {
            st.save()?;
        }
        let inner = Arc::new(Inner {
            dir: data_dir.clone(),
            store: Mutex::new(st),
            config: Mutex::new(config.clone()),
            own_write: Mutex::new(None),
            on_open: Mutex::new(None),
            stop: AtomicBool::new(false),
            hotkey_ok: AtomicBool::new(false),
        });

        let server = ipc::Server::bind(&data_dir)?;
        let addr = server.addr();
        let i2 = inner.clone();
        let ipc_thread = std::thread::Builder::new()
            .name("cliphist-ipc".into())
            .spawn(move || {
                server.serve(|| i2.stop.load(Ordering::SeqCst), |r| i2.handle(r));
            })?;

        let mut h = Handle {
            inner,
            threads: vec![ipc_thread],
            ipc_addr: addr,
            events: None,
        };
        h.events = Some(h.start_events(&config)?);
        Ok(h)
    }
}

/// Platform event sources (watcher + hotkey).
struct Events {
    #[cfg(windows)]
    _listener: platform::Listener,
    #[cfg(not(windows))]
    _hotkey: Option<platform::Hotkey>,
    stop: Arc<AtomicBool>,
    thread: Option<JoinHandle<()>>,
    hotkey: Option<keyboard_manager::Shortcut>,
}

impl Drop for Events {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::SeqCst);
        if let Some(t) = self.thread.take() {
            let _ = t.join();
        }
    }
}

const PRUNE_EVERY: Duration = Duration::from_secs(3600);

/// A running clipboard history. Dropping it stops everything.
pub struct Handle {
    inner: Arc<Inner>,
    threads: Vec<JoinHandle<()>>,
    ipc_addr: std::net::SocketAddr,
    events: Option<Events>,
}

impl Handle {
    fn start_events(&self, cfg: &Config) -> Result<Events> {
        let hotkey = cfg.hotkey();
        let stop = Arc::new(AtomicBool::new(false));
        let inner = self.inner.clone();
        #[cfg(not(windows))]
        {
            let hk = hotkey.and_then(|k| {
                let i = inner.clone();
                match platform::Hotkey::start(k, Arc::new(move || i.open_picker())) {
                    Ok(h) => Some(h),
                    Err(e) => {
                        log::warn!("clipboard history: hotkey {k}: {e:#}");
                        None
                    }
                }
            });
            inner.hotkey_ok.store(hk.is_some(), Ordering::SeqCst);
            let s2 = stop.clone();
            let thread = std::thread::Builder::new()
                .name("cliphist-watch".into())
                .spawn(move || {
                    let mut last = platform::change_count();
                    let mut pruned = Instant::now();
                    while !s2.load(Ordering::SeqCst) {
                        std::thread::sleep(platform::POLL);
                        let cc = platform::change_count();
                        if cc != last {
                            last = cc;
                            inner.on_change(cc);
                        }
                        if pruned.elapsed() > PRUNE_EVERY {
                            pruned = Instant::now();
                            prune(&inner);
                        }
                    }
                })?;
            Ok(Events {
                _hotkey: hk,
                stop,
                thread: Some(thread),
                hotkey,
            })
        }
        #[cfg(windows)]
        {
            let (tx, rx) = std::sync::mpsc::channel();
            let listener = platform::Listener::start(hotkey, tx)?;
            inner.hotkey_ok.store(listener.hotkey_ok, Ordering::SeqCst);
            let s2 = stop.clone();
            let thread = std::thread::Builder::new()
                .name("cliphist-watch".into())
                .spawn(move || {
                    let mut pruned = Instant::now();
                    while !s2.load(Ordering::SeqCst) {
                        match rx.recv_timeout(Duration::from_millis(250)) {
                            Ok(platform::Event::Changed) => {
                                inner.on_change(platform::change_count())
                            }
                            Ok(platform::Event::Hotkey) => inner.open_picker(),
                            Err(std::sync::mpsc::RecvTimeoutError::Timeout) => {}
                            Err(_) => break,
                        }
                        if pruned.elapsed() > PRUNE_EVERY {
                            pruned = Instant::now();
                            prune(&inner);
                        }
                    }
                })?;
            Ok(Events {
                _listener: listener,
                stop,
                thread: Some(thread),
                hotkey,
            })
        }
    }

    /// Called (on a worker thread) when the hotkey is pressed; the app
    /// starts the picker process from here (`powermac clipboard`, which
    /// calls [`run_picker`]).
    pub fn on_open_picker(&self, f: impl Fn() + Send + Sync + 'static) {
        if let Ok(mut g) = self.inner.on_open.lock() {
            *g = Some(Arc::new(f));
        }
    }

    /// Whether the global hotkey is registered.
    pub fn hotkey_active(&self) -> bool {
        self.inner.hotkey_ok.load(Ordering::SeqCst)
    }

    /// The data directory (also the picker's argument).
    pub fn data_dir(&self) -> &Path {
        &self.inner.dir
    }

    pub fn config(&self) -> Config {
        self.inner.cfg()
    }

    /// Apply a new configuration: limits, persistence (switching to
    /// memory-only deletes the history files), hotkey, pause.
    pub fn update(&mut self, config: Config) -> Result<()> {
        for w in config.validate() {
            log::warn!("clipboard history: {w}");
        }
        let old = self.inner.cfg();
        {
            let mut s = self.inner.store();
            if old.persist != config.persist {
                s.set_dir(config.persist.then_some(self.inner.dir.as_path()))?;
            }
            s.prune(&config, store::now_ms());
            s.save()?;
        }
        *self
            .inner
            .config
            .lock()
            .map_err(|_| anyhow!("config poisoned"))? = config.clone();
        let hotkey_changed = self.events.as_ref().map(|e| e.hotkey) != Some(config.hotkey());
        if hotkey_changed {
            self.events = None; // stop the old ones first (Windows: same hotkey id)
            self.events = Some(self.start_events(&config)?);
        }
        Ok(())
    }

    /// Pause / resume recording (in memory; the app should also save
    /// `paused` in its config).
    pub fn pause(&self, paused: bool) {
        if let Ok(mut c) = self.inner.config.lock() {
            c.paused = paused;
        }
    }

    pub fn paused(&self) -> bool {
        self.inner.cfg().paused
    }

    /// Remove every unpinned item.
    pub fn clear(&self) -> Result<()> {
        let mut s = self.inner.store();
        s.clear(true);
        s.save()
    }

    /// Remove everything, pinned items included.
    pub fn clear_all(&self) -> Result<()> {
        let mut s = self.inner.store();
        s.clear(false);
        s.save()
    }

    /// The `n` most recently used items (for the tray menu).
    pub fn recent(&self, n: usize) -> Vec<ItemSummary> {
        self.inner.store().recent(n)
    }

    /// Put item `id` on the clipboard and paste it into the frontmost app
    /// (after a short delay so a closing menu doesn't eat the keystroke).
    pub fn paste_item(&self, id: u64) -> Result<()> {
        self.inner.put_on_clipboard(id, false)?;
        if self.inner.cfg().paste_on_select {
            std::thread::spawn(|| {
                std::thread::sleep(Duration::from_millis(150));
                if let Err(e) = keyboard_manager::send_paste() {
                    log::warn!("clipboard history: paste: {e:#}");
                }
            });
        }
        Ok(())
    }

    /// Put item `id` on the clipboard without pasting.
    pub fn copy_item(&self, id: u64, plain: bool) -> Result<()> {
        self.inner.put_on_clipboard(id, plain)
    }

    pub fn set_pinned(&self, id: u64, pinned: bool) -> Result<bool> {
        let mut s = self.inner.store();
        let ok = s.set_pinned(id, pinned);
        s.save()?;
        Ok(ok)
    }

    pub fn delete(&self, id: u64) -> Result<bool> {
        let mut s = self.inner.store();
        let ok = s.delete(id);
        s.save()?;
        Ok(ok)
    }

    /// Run the picker callback as if the hotkey had been pressed.
    pub fn open_picker(&self) {
        let i = self.inner.clone();
        std::thread::spawn(move || i.open_picker());
    }

    /// Stop watching, unregister the hotkey and the picker endpoint.
    pub fn stop(mut self) {
        self.shutdown();
    }

    fn shutdown(&mut self) {
        if self.inner.stop.swap(true, Ordering::SeqCst) {
            return;
        }
        self.events = None;
        ipc::Server::wake(self.ipc_addr);
        for t in self.threads.drain(..) {
            let _ = t.join();
        }
        let _ = self.inner.store().save();
    }
}

impl Drop for Handle {
    fn drop(&mut self) {
        self.shutdown();
    }
}

fn prune(inner: &Inner) {
    let cfg = inner.cfg();
    let mut s = inner.store();
    if s.prune(&cfg, store::now_ms()) > 0 {
        let _ = s.save();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn dir(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("pm-cliphist-lib-{}-{name}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        d
    }

    #[test]
    fn data_dirs() {
        let d = default_data_dir().unwrap();
        assert!(d.ends_with("PowerMac/clipboard") || d.ends_with("PowerMac\\clipboard"));
        assert_eq!(
            data_dir_for_config(Path::new("/x/PowerMac/config.json")),
            PathBuf::from("/x/PowerMac/clipboard")
        );
    }

    /// The service's request handling, without starting the watcher.
    #[test]
    fn handle_requests() {
        let d = dir("handle");
        let cfg = Config {
            enabled: true,
            ..Default::default()
        };
        let mut st = Store::open(&d).unwrap();
        let a = st
            .add(
                content::Capture {
                    content: Content::text("alpha"),
                    ..Default::default()
                },
                &cfg,
                1,
            )
            .unwrap()
            .id();
        st.add(
            content::Capture {
                content: Content::text("beta"),
                ..Default::default()
            },
            &cfg,
            2,
        )
        .unwrap();
        let inner = Inner {
            dir: d.clone(),
            store: Mutex::new(st),
            config: Mutex::new(cfg),
            own_write: Mutex::new(None),
            on_open: Mutex::new(None),
            stop: AtomicBool::new(false),
            hotkey_ok: AtomicBool::new(false),
        };
        use ipc::Request as Q;
        let r = inner.handle(Q::List {
            query: String::new(),
            limit: 10,
        });
        assert_eq!(r.items.unwrap().len(), 2);
        assert_eq!(r.total, 2);
        assert!(
            inner
                .handle(Q::Pin {
                    id: a,
                    pinned: true
                })
                .ok
        );
        let r = inner.handle(Q::List {
            query: String::new(),
            limit: 10,
        });
        assert_eq!(r.items.unwrap()[0].id, a, "pinned first");
        assert!(!inner.handle(Q::Thumb { id: a }).ok);
        assert!(inner.handle(Q::Pause { paused: true }).paused);
        assert!(inner.handle(Q::Clear { keep_pinned: true }).ok);
        assert_eq!(inner.store().len(), 1);
        assert!(inner.handle(Q::Delete { id: a }).ok);
        assert!(!inner.handle(Q::Delete { id: a }).ok);
        // Persisted.
        assert!(Store::open(&d).unwrap().is_empty());
        let _ = std::fs::remove_dir_all(&d);
    }
}

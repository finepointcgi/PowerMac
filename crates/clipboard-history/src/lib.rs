//! Clipboard history for macOS and Windows, like Maccy / Windows' Win+V.
//!
//! - **Watching**: macOS has no clipboard notification, so a worker thread
//!   polls `NSPasteboard.changeCount` every 300 ms (reading the contents
//!   only when it changes). Windows uses `AddClipboardFormatListener` on a
//!   message-only window.
//! - **What is kept**: plain text, rich text (HTML / RTF, with the plain text
//!   as fallback), images (as PNG, plus a thumbnail) and copied files.
//!   Copying the same thing again moves it to the top. At most `maxItems`
//!   unpinned items (default 200) younger than `maxAgeDays` (30) are kept;
//!   pinned items never expire.
//! - **Privacy**: changes marked `org.nspasteboard.ConcealedType` /
//!   `TransientType` / `AutoGeneratedType` (password managers set these),
//!   Windows' `ExcludeClipboardContentFromMonitorProcessing` /
//!   `CanIncludeInClipboardHistory = 0`, and copies from excluded apps
//!   (1Password, Bitwarden, KeePassXC, Keychain Access, Passwords by default)
//!   are never read past their type list. Recording can be paused, and the
//!   history kept in memory only.
//! - **Storage**: `<config dir>/PowerMac/clipboard/` ([`default_data_dir`]):
//!   `index.json` plus `blobs/`, written atomically (see [`store`]).
//! - **Picker**: an egui window in its own process ([`run_picker`]) opened by
//!   the hotkey (Cmd+Shift+V / Win+Shift+V). It talks to the service in the
//!   tray app over loopback TCP ([`ipc`]); without a running service it
//!   reads the history files directly.
//!
//! ```no_run
//! use clipboard_history::{ClipboardHistory, Config};
//! let dir = clipboard_history::default_data_dir().unwrap();
//! let h = ClipboardHistory::start(Config { enabled: true, ..Default::default() }, dir)?;
//! h.on_open_picker(|| { /* spawn `powermac clipboard` */ });
//! for item in h.recent(10) { println!("{}", item.label(40)); }
//! h.stop();
//! # anyhow::Ok(())
//! ```

